// Reads openapi.json and writes src/schema.d.ts, src/modules/*.ts and src/client.ts.
// Run it with `bun run generate`. Never edit the files it writes.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { groupName, methodNames, pascalCase } from "./names";

interface Parameter {
  required?: boolean;
}

interface Operation {
  summary?: string;
  description?: string;
  tags: string[];
  parameters?: Parameter[];
  responses: { 200: { content: Record<string, { example?: unknown }> } };
}

interface Doc {
  paths: Record<string, { get: Operation; post?: Operation }>;
}

const SPEC_FILE = "openapi.json";
const CLIENT_CLASS = "ScrapeCreatorsClient";
const HEADER =
  "// Generated by scripts/generate.ts from openapi.json. Do not edit.\n";

// Whole sample responses are hundreds of lines each. Short examples, like a handle, stay.
function prune(key: string, value: unknown): unknown {
  const isSample = key === "example" || key === "examples";
  return isSample && typeof value === "object" && value !== null
    ? undefined
    : value;
}

// ScrapeCreators puts an em dash between spaces in some descriptions. Our docs never use one, so
// it becomes a comma. JSON syntax never holds that character, so the file stays valid.
const specText = readFileSync(SPEC_FILE, "utf8").replaceAll(" \u2014 ", ", ");
const spec: OpenAPI3 = JSON.parse(specText, prune);
const doc: Doc = JSON.parse(specText);

function docComment(op: Operation): string {
  const comment = [op.summary, op.description]
    .filter(Boolean)
    .join("\n\n")
    .replaceAll("*/", "*\\/");
  const lines = comment.split("\n").map((line) => ` * ${line}`.trimEnd());
  return `/**\n${lines.join("\n")}\n */`;
}

// The spec has no response schemas, only one example for each endpoint. Four endpoints answer
// with a list, and the rest with an object.
function unwrapName(op: Operation): "unwrap" | "unwrapList" {
  const examples = Object.values(op.responses[200].content);
  return examples.some(({ example }) => Array.isArray(example))
    ? "unwrapList"
    : "unwrap";
}

interface Method {
  name: string;
  path: string;
  verb: "GET" | "POST";
  op: Operation;
}

function renderMethod({ name, path, verb, op }: Method): string {
  const unwrap = unwrapName(op);
  if (verb === "POST") {
    const call = `this.api.POST("${path}", { body, signal: options?.signal })`;
    return `${docComment(op)}\n${name}(body: Body<"${path}">, options?: CallOptions) {\n  return ${unwrap}(${call});\n}`;
  }
  const params = op.parameters ?? [];
  const args = ["options?: CallOptions"];
  let init = "{ signal: options?.signal }";
  if (params.length) {
    const optional = params.some((param) => param.required) ? "" : "?";
    args.unshift(`query${optional}: Query<"${path}">`);
    init = "{ params: { query }, signal: options?.signal }";
  }
  return `${docComment(op)}\n${name}(${args.join(", ")}) {\n  return ${unwrap}(this.api.GET("${path}", ${init}));\n}`;
}

function renderModule(group: string, methods: Method[]): string {
  const imports = new Set(["CallOptions"]);
  for (const { op, verb } of methods) {
    imports.add(unwrapName(op));
    if (verb === "POST") imports.add("Body");
    else if (op.parameters?.length) imports.add("Query");
  }
  const names = [...imports]
    .sort()
    .map((name) => (/^[A-Z]/.test(name) ? `type ${name}` : name));
  return `${HEADER}import type { Client } from "openapi-fetch";
import { ${names.join(", ")} } from "../http";
import type { paths } from "../schema";

export class ${pascalCase(group)}Module {
  constructor(private readonly api: Client<paths>) {}

${methods.map(renderMethod).join("\n\n")}
}
`;
}

function renderClient(groupNames: string[]): string {
  const modules = groupNames.map((name) => ({
    name,
    className: `${pascalCase(name)}Module`,
  }));
  return `${HEADER}import type { Client } from "openapi-fetch";
import { createApi, type ScrapeCreatorsConfig } from "./http";
${modules.map(({ name, className }) => `import { ${className} } from "./modules/${name}";`).join("\n")}
import type { paths } from "./schema";

export class ${CLIENT_CLASS} {
  readonly api: Client<paths>;
${modules.map(({ name, className }) => `  readonly ${name}: ${className};`).join("\n")}

  constructor(config: ScrapeCreatorsConfig | string) {
    this.api = createApi(typeof config === "string" ? { apiKey: config } : config);
${modules.map(({ name, className }) => `    this.${name} = new ${className}(this.api);`).join("\n")}
  }
}
`;
}

const pathsByGroup = new Map<string, string[]>();
for (const [path, { get }] of Object.entries(doc.paths)) {
  const group = groupName(get.tags[0]);
  pathsByGroup.set(group, [...(pathsByGroup.get(group) ?? []), path]);
}

// A path that also takes a POST gets a second method, `<name>Post`, with the parameters in the
// body. ScrapeCreators asks for it when a cursor grows too long for a URL.
const groups = new Map<string, Method[]>();
for (const [group, paths] of pathsByGroup) {
  const names = methodNames(group, paths);
  const methods = paths.flatMap((path, index): Method[] => {
    const { get, post } = doc.paths[path];
    const getMethod: Method = {
      name: names[index],
      path,
      verb: "GET",
      op: get,
    };
    if (!post) return [getMethod];
    return [
      getMethod,
      { name: `${names[index]}Post`, path, verb: "POST", op: post },
    ];
  });
  groups.set(group, methods);
}

rmSync("src/modules", { recursive: true, force: true });
mkdirSync("src/modules", { recursive: true });
writeFileSync("src/schema.d.ts", astToString(await openapiTS(spec)));
for (const [group, methods] of groups) {
  writeFileSync(`src/modules/${group}.ts`, renderModule(group, methods));
}
writeFileSync("src/client.ts", renderClient([...groups.keys()]));
console.log(
  [...groups]
    .map(([group, methods]) => `${group}: ${methods.length}`)
    .join(", "),
);
